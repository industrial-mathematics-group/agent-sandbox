#!/bin/bash
# Collects the allowlist and writes the proxy configuration.
#
# Sources (all merged, duplicates removed):
#   /etc/agent-sandbox/lists/base.list            always
#   /etc/agent-sandbox/lists/<profile>.list       for each GATEWAY_PROFILES entry
#   /etc/agent-sandbox/extra.list                 mounted from the host, if present
#   GATEWAY_EXTRA_DOMAINS                         space or comma separated
#   JULIA_PKG_SERVER                              its host, if set
#
# GATEWAY_UPSTREAM_PROXY=host:port chains the proxy to an existing HTTP proxy
# (corporate networks); the firewall then only lets the proxy talk to that one.
#
# Output in /run/agent-gateway/:
#   domains          one entry per line ("*.example.com" = domain + subdomains)
#   filter           tinyproxy filter (extended regex, one per entry)
#   tinyproxy.conf
set -euo pipefail
IFS=$'\n\t'

LISTS=/etc/agent-sandbox/lists
OUT=/run/agent-gateway
MODE=${GATEWAY_MODE:-standard}
PROFILES=${GATEWAY_PROFILES:-}
EXTRA=${GATEWAY_EXTRA_DOMAINS:-${FIREWALL_EXTRA_DOMAINS:-}}   # old name still accepted
PROXY_PORT=${GATEWAY_PROXY_PORT:-3128}

mkdir -p "$OUT"

entries=()
read_list() {
    local f=$1 line
    while IFS= read -r line || [ -n "$line" ]; do
        line=${line%%#*}
        line=${line//[[:space:]]/}
        if [ -n "$line" ]; then entries+=("$line"); fi
    done < "$f"
}

read_list "$LISTS/base.list"
IFS=' ,' read -r -a profiles <<< "$PROFILES"
for p in "${profiles[@]}"; do
    [ -z "$p" ] || [ "$p" = base ] && continue
    if [[ ! "$p" =~ ^[a-z0-9_-]+$ ]] || [ ! -f "$LISTS/$p.list" ]; then
        echo "ERROR: unknown profile '$p' (available: $(cd "$LISTS" && ls ./*.list | sed 's|^\./||; s|\.list$||' | tr '\n' ' '))" >&2
        exit 1
    fi
    read_list "$LISTS/$p.list"
done
[ -f /etc/agent-sandbox/extra.list ] && read_list /etc/agent-sandbox/extra.list
if [ -n "$EXTRA" ]; then
    IFS=' ,' read -r -a extra <<< "$EXTRA"
    for d in "${extra[@]}"; do if [ -n "$d" ]; then entries+=("$d"); fi; done
fi
if [ -n "${JULIA_PKG_SERVER:-}" ]; then
    h=${JULIA_PKG_SERVER#*://}; h=${h%%/*}; h=${h%%:*}
    entries+=("$h")
fi

: > "$OUT/domains.tmp"
for e in "${entries[@]}"; do
    e=${e,,}
    if [[ ! "$e" =~ ^(\*\.)?[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$ ]]; then
        echo "ERROR: invalid allowlist entry '$e' (expected host.name or *.host.name)" >&2
        exit 1
    fi
    echo "$e" >> "$OUT/domains.tmp"
done
sort -u "$OUT/domains.tmp" > "$OUT/domains"
rm -f "$OUT/domains.tmp"

# Regex per entry, anchored. tinyproxy matches it against the requested host.
: > "$OUT/filter"
while IFS= read -r e; do
    if [[ "$e" == \*.* ]]; then
        d=${e#\*.}
        printf '(^|\\.)%s$\n' "${d//./\\.}" >> "$OUT/filter"
    else
        printf '^%s$\n' "${e//./\\.}" >> "$OUT/filter"
    fi
done < "$OUT/domains"

{
    cat <<EOF
# Generated by render-config.sh at gateway start. Edit the lists, not this file.
User agentproxy
Group agentproxy
Listen 127.0.0.1
Port $PROXY_PORT
Timeout 600
MaxClients 256
Allow 127.0.0.1
DisableViaHeader Yes
LogLevel ${GATEWAY_LOG_LEVEL:-Connect}
# CONNECT only to https and ssh
ConnectPort 443
ConnectPort 22
EOF
    if [ -n "${GATEWAY_UPSTREAM_PROXY:-}" ]; then
        [[ "$GATEWAY_UPSTREAM_PROXY" =~ ^[A-Za-z0-9.-]+:[0-9]{1,5}$ ]] \
            || { echo "ERROR: GATEWAY_UPSTREAM_PROXY must be host:port" >&2; exit 1; }
        echo "Upstream http $GATEWAY_UPSTREAM_PROXY"
    fi
    if [ "$MODE" != open ]; then
        cat <<EOF
FilterDefaultDeny Yes
FilterType ere
FilterURLs Off
FilterCaseSensitive Off
Filter "$OUT/filter"
EOF
    fi
} > "$OUT/tinyproxy.conf"

echo "Allowlist: $(wc -l < "$OUT/domains") entries (profiles: base${PROFILES:+ $PROFILES})"
